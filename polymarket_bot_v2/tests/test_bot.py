def test_slug_handles_daylight_saving():
    summer = datetime(2026, 7, 1, 14, tzinfo=timezone.utc)     # 10am EDT
    winter = datetime(2026, 12, 1, 15, tzinfo=timezone.utc)    # 10am EST
    assert hourly_slug(summer) == "bitcoin-up-or-down-july-1-10am-et"
    assert hourly_slug(winter) == "bitcoin-up-or-down-december-1-10am-et"


def test_book_vwap_and_depth():
    b = OrderBook(bids=[Level(0.48, 10)], asks=[Level(0.50, 10), Level(0.52, 10), Level(0.60, 100)])
    assert b.ask_depth_usd(0.02) == pytest.approx(0.50 * 10 + 0.52 * 10)
    tokens, avg = b.buy_fill(10.0)                   # 5$ at 0.50 then 5$ at 0.52
    assert tokens == pytest.approx(10 + 5 / 0.52)
    assert 0.50 < avg < 0.52


# ------------------------------------------------------------------ model
def simulate_ewma(lam, n, seed, sigma=SIG_MIN):
    """Returns generated by a true EWMA variance process with parameter lam."""
    rng = np.random.default_rng(seed)
    var, r = sigma ** 2, np.empty(n)
    for i in range(n):
        r[i] = np.sqrt(var) * rng.standard_normal()
        var = lam * var + (1 - lam) * r[i] ** 2
    return r


@pytest.mark.parametrize("true_lam", [0.90, 0.95, 0.98])
def test_mle_recovers_lambda(true_lam):
    est = [fit_lambda(simulate_ewma(true_lam, 3000, seed)) for seed in range(5)]
    assert np.mean(est) == pytest.approx(true_lam, abs=0.015)


def test_calibration_reports_fitted_lambda():
    r = simulate_ewma(0.90, 500, seed=7)
    closes = 100_000 * np.exp(np.concatenate([[0], np.cumsum(r)]))
    v = VolatilityModel(0.94, 3.0)
    v.calibrate(closes)
    assert v.fit_report["lambda_initial"] == 0.94
    assert 0.80 <= v.lam <= 0.999 and v.lam == v.fit_report["lambda_fitted"]
    assert v.fit_report["loglik_gain_vs_initial"] >= 0          # MLE never fits worse than 0.94
    assert v.half_life_minutes == pytest.approx(np.log(0.5) / np.log(v.lam))


def test_vol_ignores_jumps():
    rng = np.random.default_rng(1)
    r = rng.normal(0, SIG_MIN, 500)
    r[[100, 300]] = 0.02                             # two 25-sigma jumps
    closes = 100_000 * np.exp(np.concatenate([[0], np.cumsum(r)]))
    v = VolatilityModel(0.94, 3.0)
    v.calibrate(closes)
    assert len(v.jumps) >= 2
    assert 0.5 * SIG_MIN < v.sigma_minute < 1.6 * SIG_MIN


@pytest.mark.parametrize("moneyness", [-0.004, -0.001, 0.0, 0.002])
def test_closed_form_matches_monte_carlo(moneyness):
    s, k, tau = 100_000 * (1 + moneyness), 100_000, 30
    assert prob_up(s, k, tau, SIG_MIN, JP) == pytest.approx(prob_up_mc(s, k, tau, SIG_MIN, JP), abs=0.003)


def test_pricing_limits_and_prudence():
    assert prob_up(101_000, 100_000, 0, SIG_MIN, JP) == 1.0
    assert prob_up(100_500, 100_000, 30, SIG_MIN, JP) > 0.5

def book(bid, ask, size=1000.0):
    return OrderBook(bids=[Level(bid, size)], asks=[Level(ask, size)])


def market(bid_yes, ask_yes, minutes_left=30.0, now=1_000_000.0):
    return Market("m", "q", "y", "n", expiry_ts=now + minutes_left * 60, strike=100_000.0,
                  book_yes=book(bid_yes, ask_yes), book_no=book(1 - ask_yes, 1 - bid_yes))



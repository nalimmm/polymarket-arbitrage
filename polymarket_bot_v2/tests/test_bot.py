@pytest.mark.parametrize("q,ask,expected_full,expected_usd", [
    (0.48, 0.45, 0.046, 1.15),     # small edge
    (0.46, 0.42, 0.061, 1.52),     # medium edge
    (0.66, 0.58, 0.181, 2.50),     # large edge -> 2.5% cap
])
def test_kelly_examples(q, ask, expected_full, expected_usd):
    s = Sizer(CFG.sizing, 0.02)
    d = s.size(q, ask, equity=100, outcome_exposure=0, total_exposure=0, depth_usd=1000)
    assert kelly_binary(q, ask, 0.02) == pytest.approx(expected_full, abs=0.001)
    assert d.usd == pytest.approx(expected_usd, abs=0.01)


